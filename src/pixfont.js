export const GLYPH_H = 5;

export function glyph(ch) {
  const g = GLYPHS[ch.toUpperCase()];
  if (!g) throw new Error(`нет глифа «${ch}»`);
  return g;
}

export const textWidth = (s) => (s.length ? s.length * 4 - 1 : 0);

// plot(x, y): закрасить пиксель экрана.
export function drawText(plot, s, x, y) {
  [...s].forEach((ch, n) => {
    glyph(ch).forEach((row, j) => [...row].forEach((p, i) => p === '#' && plot(x + n * 4 + i, y + j)));
  });
}
